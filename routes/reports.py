"""LoanWise AI - PDF reports (ReportLab).

Two reports:
  1. Per-prediction PDF: branding, applicant details, the five model
     votes, voting summary, final decision, timestamp, disclaimer.
  2. Model performance PDF: dataset info, preprocessing, 70/30 split,
     the five models' metrics and the best model's confusion matrix.
"""
import io
import json
import os
from datetime import datetime

from flask import Blueprint, current_app, flash, redirect, send_file, url_for
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (Paragraph, SimpleDocTemplate, Spacer, Table,
                                TableStyle)

from database.db import Prediction
from routes.common import active_dataset, login_required

reports_bp = Blueprint("reports", __name__)
NAVY = colors.HexColor("#14243A")
BLUE = colors.HexColor("#315EAB")
TEAL = colors.HexColor("#24B8A5")
GREY = colors.HexColor("#718096")
DISCLAIMER = ("Educational use only. This report was generated by a college "
              "mini project (LoanWise AI) for learning purposes and is not a "
              "real lending decision. Do not use it to approve or reject an "
              "actual loan application.")


def _styles():
    styles = getSampleStyleSheet()
    styles["Title"].textColor = NAVY
    styles["Heading2"].textColor = NAVY
    return styles


def _table(data, widths=None):
    table = Table(data, colWidths=widths, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F4F7FB")]),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
    ]))
    return table


@reports_bp.route("/reports/prediction/<int:prediction_id>.pdf")
@login_required
def prediction_pdf(prediction_id):
    record = Prediction.query.get_or_404(prediction_id)
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4,
                            title=f"LoanWise AI - Prediction #{record.id}")
    styles = _styles()
    story = [
        Paragraph("LoanWise AI", styles["Title"]),
        Paragraph("Machine Learning-Based Loan Approval Decision Support System",
                  styles["Normal"]),
        Spacer(1, 6 * mm),
        Paragraph(f"Prediction Report - ID #{record.id}", styles["Heading2"]),
        Paragraph(f"Generated: {record.created_at.strftime('%d %b %Y, %I:%M %p')}",
                  styles["Normal"]),
        Spacer(1, 4 * mm),
        Paragraph("Applicant Information", styles["Heading2"]),
        _table([
            ["Field", "Value"],
            ["Number of Dependents", str(record.no_of_dependents)],
            ["Education", record.education],
            ["Employment Status", record.self_employed],
            ["Annual Income", f"Rs. {record.income_annum:,.0f}"],
            ["Loan Amount", f"Rs. {record.loan_amount:,.0f}"],
            ["Loan Term", f"{record.loan_term} years"],
            ["CIBIL Score", str(record.cibil_score)],
            ["Residential Assets", f"Rs. {record.residential_assets_value:,.0f}"],
            ["Commercial Assets", f"Rs. {record.commercial_assets_value:,.0f}"],
            ["Luxury Assets", f"Rs. {record.luxury_assets_value:,.0f}"],
            ["Bank Assets", f"Rs. {record.bank_asset_value:,.0f}"],
        ]),
        Spacer(1, 5 * mm),
        Paragraph("Model Predictions", styles["Heading2"]),
        _table([["Model", "Prediction"]] +
               [[name, "Approve" if v else "Reject"] for name, v in record.votes()]),
        Spacer(1, 5 * mm),
        Paragraph("Voting Summary", styles["Heading2"]),
        Paragraph(f"Approval votes: {record.approval_votes} &nbsp;&nbsp; "
                  f"Rejection votes: {record.rejection_votes}", styles["Normal"]),
        Paragraph(f"<b>Final Decision: {record.final_decision}</b>", styles["Normal"]),
        Spacer(1, 6 * mm),
        Paragraph(DISCLAIMER, styles["Normal"]),
    ]
    doc.build(story)
    buffer.seek(0)
    return send_file(buffer, mimetype="application/pdf", as_attachment=True,
                     download_name=f"loanwise_prediction_{record.id}.pdf")


@reports_bp.route("/reports/performance.pdf")
@login_required
def performance_pdf():
    ds = active_dataset()
    if ds is None or not ds.metrics_json:
        flash("Please upload and process a loan dataset first.", "error")
        return redirect(url_for("dataset.performance"))
    metrics = json.loads(ds.metrics_json)
    best = max(metrics, key=lambda n: (metrics[n]["accuracy"], metrics[n]["f1"]))
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, title="LoanWise AI - Model Performance Report")
    styles = _styles()
    rows = [["Model", "Accuracy", "Precision", "Recall", "F1-Score"]]
    for name, m in metrics.items():
        rows.append([name, f"{m['accuracy']*100:.2f}%", f"{m['precision']*100:.2f}%",
                     f"{m['recall']*100:.2f}%", f"{m['f1']*100:.2f}%"])
    cm = metrics[best]["confusion_matrix"]
    story = [
        Paragraph("LoanWise AI - Model Performance Report", styles["Title"]),
        Paragraph(f"Generated: {datetime.now().strftime('%d %b %Y, %I:%M %p')}", styles["Normal"]),
        Spacer(1, 5 * mm),
        Paragraph("Dataset Information", styles["Heading2"]),
        Paragraph(f"File: {ds.original_filename}<br/>"
                  f"Rows: {ds.total_rows:,} &nbsp; Columns: {ds.total_columns} &nbsp; "
                  f"Missing values: {ds.missing_values} &nbsp; Duplicates: {ds.duplicate_rows}<br/>"
                  f"Approved: {ds.approved:,} &nbsp; Rejected: {ds.rejected:,}", styles["Normal"]),
        Spacer(1, 4 * mm),
        Paragraph("Preprocessing", styles["Heading2"]),
        Paragraph("loan_id dropped from features. Education encoded Graduate=1 / "
                  "Not Graduate=0. Self-employed encoded Yes=1 / No=0. "
                  "Loan status encoded Approved=1 / Rejected=0. "
                  "StandardScaler fitted on training data only. "
                  f"Split: 70% train ({ds.train_count:,}) / 30% test ({ds.test_count:,}), "
                  "random_state=42, stratified.", styles["Normal"]),
        Spacer(1, 4 * mm),
        Paragraph("Model Metrics (test set)", styles["Heading2"]),
        _table(rows),
        Spacer(1, 5 * mm),
        Paragraph(f"Best model: {best} "
                  f"({metrics[best]['accuracy']*100:.2f}% accuracy)", styles["Heading2"]),
        Paragraph(f"Best model confusion matrix (rows = true, columns = predicted): "
                  f"Rejected/Rejected {cm[0][0]}, Rejected/Approved {cm[0][1]}, "
                  f"Approved/Rejected {cm[1][0]}, Approved/Approved {cm[1][1]}.",
                  styles["Normal"]),
        Spacer(1, 6 * mm),
        Paragraph(DISCLAIMER, styles["Normal"]),
    ]
    doc.build(story)
    buffer.seek(0)
    return send_file(buffer, mimetype="application/pdf", as_attachment=True,
                     download_name="loanwise_model_performance.pdf")
